import { execFileSync } from "node:child_process";
import {
  publicBuild,
  releaseModes,
  validateRelease,
  validateVersion,
} from "./build-config.mjs";
import { randomBytes } from "node:crypto";
import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { parseArgs } from "node:util";

export function settings(args) {
  const { values } = parseArgs({
    args,
    options: {
      mode: { type: "string", default: "simulator" },
      "api-origin": { type: "string" },
      "rp-id": { type: "string" },
      "team-id": { type: "string" },
      "bundle-id": { type: "string" },
      version: { type: "string" },
      "build-number": { type: "string" },
    },
  });
  if (
    !["simulator", "device", "device-demo", ...releaseModes].includes(
      values.mode,
    )
  )
    throw new Error(
      "mode must be simulator, device, device-demo, staging, or production",
    );
  const simulator = values.mode === "simulator";
  const demo = values.mode === "device-demo";
  const release = releaseModes.includes(values.mode);
  const api = new URL(
    values["api-origin"] ?? (simulator ? "http://localhost:4310" : ""),
  );
  if (
    api.username ||
    api.password ||
    api.pathname !== "/" ||
    api.search ||
    api.hash ||
    (simulator
      ? api.origin !== "http://localhost:4310"
      : api.protocol !== "https:")
  ) {
    throw new Error(
      "Use http://localhost:4310 for simulator mode, or an HTTPS origin without a path or credentials for device mode",
    );
  }
  if (demo && !/^[a-z0-9-]+\.trycloudflare\.com$/.test(api.hostname))
    throw new Error(
      "Device demo must use a dedicated temporary trycloudflare.com API, never production",
    );
  const rp = simulator || demo ? "passkeys.invalid" : values["rp-id"];
  if (
    !rp ||
    !/^(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$/i.test(rp) ||
    (!simulator && !demo && rp.toLowerCase().endsWith(".invalid"))
  ) {
    throw new Error(
      "Device mode requires --rp-id with a real domain you control",
    );
  }
  const bundle =
    values["bundle-id"] ??
    (demo
      ? "com.bitstockerz.research.demo"
      : values.mode === "staging"
        ? "com.bitstockerz.research.staging"
        : "com.bitstockerz.research");
  if (!/^[a-zA-Z][a-zA-Z0-9-]*(?:\.[a-zA-Z0-9-]+)+$/.test(bundle))
    throw new Error("Invalid bundle identifier");
  if (demo && !bundle.toLowerCase().endsWith(".demo"))
    throw new Error("Device demo bundle identifier must end in .demo");
  const team = values["team-id"];
  if (team && !/^[A-Z0-9]{10}$/.test(team))
    throw new Error("Apple Team ID must be ten uppercase letters/digits");
  const config = {
    mode: values.mode,
    apiOrigin: api.origin,
    rpId: rp.toLowerCase(),
    bundleId: bundle,
    teamId: team,
    version: values.version ?? (release ? undefined : "1.0.0"),
    buildNumber: values["build-number"] ?? (release ? undefined : "1"),
  };
  validateVersion(config);
  if (release)
    validateRelease({
      ...config,
      sourceRevision: "0".repeat(40),
      sourceDirty: false,
    });
  return config;
}

export function environmentSource(config) {
  const build = publicBuild(config);
  return `// Generated by ios:prepare; ignored.
import type { NativeBuildInfo } from '../app/core/native/build-info';
export const environment = ${JSON.stringify({ production: config.mode !== "simulator", apiBaseUrl: config.apiOrigin, nativeMode: releaseModes.includes(config.mode) ? "device" : config.mode, prototypeAccessKey: config.demoAccessKey, nativeBuild: build }, null, 2)} as { production: boolean; apiBaseUrl: string; nativeMode: 'web' | 'simulator' | 'device' | 'device-demo'; prototypeAccessKey?: string; nativeBuild?: NativeBuildInfo };
`;
}

export function prepare(
  args,
  { root = fileURLToPath(new URL("../../", import.meta.url)) } = {},
) {
  const config = settings(args);
  config.sourceRevision = execFileSync("git", ["rev-parse", "HEAD"], {
    cwd: root,
    encoding: "utf8",
  }).trim();
  config.sourceDirty = Boolean(
    execFileSync("git", ["status", "--porcelain", "--untracked-files=normal"], {
      cwd: root,
      encoding: "utf8",
    }).trim(),
  );
  if (releaseModes.includes(config.mode)) validateRelease(config);
  const build = publicBuild(config);
  const demo = config.mode === "device-demo";
  if (demo) config.demoAccessKey = randomBytes(32).toString("hex");
  const write = (name, contents) => {
    writeFileSync(resolve(root, name), contents, { mode: 0o600 });
    chmodSync(resolve(root, name), 0o600);
  };
  write(
    "apps/web/src/environments/environment.ios.local.ts",
    environmentSource(config),
  );
  write(
    "apps/web/ios/App/App/Prototype.xcconfig",
    `BITSTOCKERZ_RP_ID = ${config.rpId}\nBITSTOCKERZ_BUNDLE_ID = ${config.bundleId}\nBITSTOCKERZ_ENTITLEMENTS = App/${demo ? "Demo" : "App"}.entitlements\nBITSTOCKERZ_DISPLAY_NAME = BitStockerz\nBITSTOCKERZ_CHANNEL = ${config.mode}\nBITSTOCKERZ_FINGERPRINT = ${build.fingerprint}\nBITSTOCKERZ_VERSION = ${config.version}\nBITSTOCKERZ_BUILD_NUMBER = ${config.buildNumber}\n${config.teamId ? `DEVELOPMENT_TEAM = ${config.teamId}\n` : ""}`,
  );
  write(
    "apps/web/.ios-prototype.local.json",
    JSON.stringify(config, null, 2) + "\n",
  );
  write(
    "apps/web/public/ios-build.local.json",
    JSON.stringify(build, null, 2) + "\n",
  );
  mkdirSync(resolve(root, "artifacts/ios-setup"), { recursive: true });
  if (
    config.teamId &&
    (config.mode === "device" || releaseModes.includes(config.mode))
  ) {
    write(
      "artifacts/ios-setup/apple-app-site-association",
      JSON.stringify(
        {
          webcredentials: { apps: [`${config.teamId}.${config.bundleId}`] },
        },
        null,
        2,
      ) + "\n",
    );
  }
  console.log(
    `Prepared ${config.mode} prototype for ${config.apiOrigin}. Next: npm run ios:sync`,
  );
  if (config.mode === "device" || releaseModes.includes(config.mode))
    console.log(
      "Serve the association file publicly on the RP domain. Do not put the production beta proxy key in this app.",
    );
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    prepare(process.argv.slice(2));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
